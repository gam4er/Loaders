            if (codecs.Contains(5))
            {
                builder.AppendLine("        private static byte[] DecodeCodec5(byte[] metadata, byte[] payload, int charCount)");
                builder.AppendLine("        {");
                builder.AppendLine("            if (metadata.Length != 1) throw new System.InvalidOperationException(\"Invalid reverse XOR metadata.\");");
