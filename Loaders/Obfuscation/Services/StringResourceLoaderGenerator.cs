        private static void AppendCommonHelpers(StringBuilder builder, ISet<byte> codecs)
        {
            if (codecs.Contains(2) || codecs.Contains(4))
            {
                builder.AppendLine("        private static void ApplyLcgXor(byte[] data, uint seed)");
                builder.AppendLine("        {");
                builder.AppendLine("            var state = seed;");
                builder.AppendLine("            for (var i = 0; i < data.Length; i++)");
                builder.AppendLine("            {");
                builder.AppendLine("                state = unchecked(state * 1664525u + 1013904223u);");
                builder.AppendLine("                data[i] ^= (byte)(state >> 24);");
                builder.AppendLine("            }");
                builder.AppendLine("        }");
                builder.AppendLine();
            }

            if (codecs.Contains(3) || codecs.Contains(4))
            {
                builder.AppendLine("        private static byte[] Decompress(byte[] payload)");
                builder.AppendLine("        {");
                builder.AppendLine("            using (var input = new System.IO.MemoryStream(payload))");
                builder.AppendLine("            using (var gzip = new System.IO.Compression.GZipStream(input, System.IO.Compression.CompressionMode.Decompress))");
                builder.AppendLine("            using (var output = new System.IO.MemoryStream())");
                builder.AppendLine("            {");
                builder.AppendLine("                gzip.CopyTo(output);");
                builder.AppendLine("                return output.ToArray();");
                builder.AppendLine("            }");
                builder.AppendLine("        }");
                builder.AppendLine();
            }

            builder.AppendLine("        private static byte[] Clone(byte[] bytes)");
            builder.AppendLine("        {");
            builder.AppendLine("            var clone = new byte[bytes.Length];");
            builder.AppendLine("            System.Buffer.BlockCopy(bytes, 0, clone, 0, bytes.Length);");
            builder.AppendLine("            return clone;");
            builder.AppendLine("        }");
            builder.AppendLine();
            builder.AppendLine("        private static byte[] Slice(byte[] bytes, int offset, int length)");
            builder.AppendLine("        {");
            builder.AppendLine("            ValidateRange(offset, length, bytes.Length, \"slice\");");
            builder.AppendLine("            var result = new byte[length];");
            builder.AppendLine("            System.Buffer.BlockCopy(bytes, offset, result, 0, length);");
            builder.AppendLine("            return result;");
            builder.AppendLine("        }");
            builder.AppendLine();
            builder.AppendLine("        private static string StringFromUtf16Le(byte[] bytes, int charCount)");
