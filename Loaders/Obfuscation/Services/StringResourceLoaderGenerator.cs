                builder.AppendLine("            if (metadata.Length != 0 || payload.Length != checked(charCount * 8)) throw new System.InvalidOperationException(\"Invalid UTF-16 delta payload.\");");
                builder.AppendLine("            var output = new byte[checked(charCount * 2)];");
                builder.AppendLine("            for (var i = 0; i < charCount; i++)");
                builder.AppendLine("            {");
                builder.AppendLine("                var masked = ReadUInt32(payload, i * 8);");
                builder.AppendLine("                var delta = ReadUInt32(payload, i * 8 + 4);");
                builder.AppendLine("                WriteChar(output, i, checked((ushort)(masked - delta)));");
                builder.AppendLine("            }");
                builder.AppendLine("            return output;");
                builder.AppendLine("        }");
                builder.AppendLine();
