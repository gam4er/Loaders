                builder.AppendLine("            var output = new byte[expected];");
                builder.AppendLine("            for (var i = 0; i < output.Length; i++)");
                builder.AppendLine("            {");
                builder.AppendLine("                var source = ReadInt32(metadata, i * 4);");
                builder.AppendLine("                if (source < 0 || source >= payload.Length) throw new System.InvalidOperationException(\"Invalid byte permutation index.\");");
                builder.AppendLine("                output[i] = payload[source];");
                builder.AppendLine("            }");
                builder.AppendLine("            return output;");
