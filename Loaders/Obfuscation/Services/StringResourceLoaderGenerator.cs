    internal static class StringResourceLoaderGenerator
    {
        public static string Generate(
            string generatedNamespace,
            string generatedTypeName,
            string manifestResourceName,
            IReadOnlyCollection<byte> usedCodecIds)
        {
            if (string.IsNullOrWhiteSpace(generatedNamespace))
            {
                throw new ArgumentException("Generated namespace is required.", nameof(generatedNamespace));
            }

            if (string.IsNullOrWhiteSpace(generatedTypeName))
            {
                throw new ArgumentException("Generated type name is required.", nameof(generatedTypeName));
            }

            if (string.IsNullOrWhiteSpace(manifestResourceName))
            {
                throw new ArgumentException("Manifest resource name is required.", nameof(manifestResourceName));
            }

            var codecs = new HashSet<byte>(usedCodecIds ?? Array.Empty<byte>());
            var builder = new StringBuilder();
            builder.AppendLine("// <auto-generated />");
            builder.AppendLine("// String resource format v1: LSR1 header, sorted descriptors, metadata region, payload region.");
            builder.AppendLine("namespace " + generatedNamespace);
            builder.AppendLine("{");
            builder.AppendLine("    internal static class " + generatedTypeName);
            builder.AppendLine("    {");
            builder.AppendLine("        private const int Magic = " + StringResourceSerializer.Magic.ToString(CultureInfo.InvariantCulture) + ";");
            builder.AppendLine("        private const int Version = " + StringResourceSerializer.FormatVersion.ToString(CultureInfo.InvariantCulture) + ";");
            builder.AppendLine("        private const int HeaderSize = " + StringResourceSerializer.HeaderSize.ToString(CultureInfo.InvariantCulture) + ";");
            builder.AppendLine("        private const int DescriptorSize = " + StringResourceSerializer.DescriptorSize.ToString(CultureInfo.InvariantCulture) + ";");
            builder.AppendLine("        private const string ResourceName = " + Quote(manifestResourceName) + ";");
            builder.AppendLine("        private static readonly object InitLock = new object();");
            builder.AppendLine("        private static readonly object CacheLock = new object();");
            builder.AppendLine("        private static byte[] Blob;");
            builder.AppendLine("        private static Entry[] Entries;");
            builder.AppendLine("        private static string[] Cache;");
            builder.AppendLine();
            builder.AppendLine("        internal static string Get(int token)");
            builder.AppendLine("        {");
            builder.AppendLine("            EnsureInitialized();");
            builder.AppendLine("            var entryIndex = FindEntry(token);");
            builder.AppendLine("            if (entryIndex < 0)");
            builder.AppendLine("            {");
            builder.AppendLine("                throw new System.InvalidOperationException(\"String resource entry was not found for token 0x\" + unchecked((uint)token).ToString(\"X8\", System.Globalization.CultureInfo.InvariantCulture) + \".\");");
            builder.AppendLine("            }");
            builder.AppendLine();
            builder.AppendLine("            var entry = Entries[entryIndex];");
            builder.AppendLine("            var cached = Cache[entry.CacheIndex];");
            builder.AppendLine("            if (cached != null)");
            builder.AppendLine("            {");
            builder.AppendLine("                return cached;");
            builder.AppendLine("            }");
            builder.AppendLine();
            builder.AppendLine("            lock (CacheLock)");
            builder.AppendLine("            {");
            builder.AppendLine("                cached = Cache[entry.CacheIndex];");
            builder.AppendLine("                if (cached == null)");
            builder.AppendLine("                {");
            builder.AppendLine("                    cached = Decode(entry);");
            builder.AppendLine("                    Cache[entry.CacheIndex] = cached;");
            builder.AppendLine("                }");
            builder.AppendLine();
            builder.AppendLine("                return cached;");
            builder.AppendLine("            }");
            builder.AppendLine("        }");
            builder.AppendLine();
            AppendInitialization(builder, generatedTypeName);
            AppendDecode(builder, codecs);
            AppendCodecMethods(builder, codecs);
            AppendCommonHelpers(builder, codecs);
            AppendEntryType(builder);
            builder.AppendLine("    }");
            builder.AppendLine("}");
            return builder.ToString();
        }

        private static void AppendInitialization(StringBuilder builder, string generatedTypeName)
        {
            builder.AppendLine("        private static void EnsureInitialized()");
            builder.AppendLine("        {");
            builder.AppendLine("            if (Entries != null)");
            builder.AppendLine("            {");
            builder.AppendLine("                return;");
            builder.AppendLine("            }");
            builder.AppendLine();
            builder.AppendLine("            lock (InitLock)");
            builder.AppendLine("            {");
            builder.AppendLine("                if (Entries != null)");
            builder.AppendLine("                {");
            builder.AppendLine("                    return;");
            builder.AppendLine("                }");
            builder.AppendLine();
            builder.AppendLine("                var assembly = typeof(" + generatedTypeName + ").Assembly;");
            builder.AppendLine("                using (var stream = assembly.GetManifestResourceStream(ResourceName))");
            builder.AppendLine("                {");
            builder.AppendLine("                    if (stream == null)");
            builder.AppendLine("                    {");
            builder.AppendLine("                        throw new System.InvalidOperationException(\"String resource '\" + ResourceName + \"' was not found in assembly '\" + assembly.FullName + \"'.\");");
            builder.AppendLine("                    }");
            builder.AppendLine();
            builder.AppendLine("                    using (var memory = new System.IO.MemoryStream())");
            builder.AppendLine("                    {");
            builder.AppendLine("                        stream.CopyTo(memory);");
            builder.AppendLine("                        Blob = memory.ToArray();");
            builder.AppendLine("                    }");
            builder.AppendLine("                }");
            builder.AppendLine();
            builder.AppendLine("                ParseIndex();");
            builder.AppendLine("            }");
            builder.AppendLine("        }");
            builder.AppendLine();
            builder.AppendLine("        private static void ParseIndex()");
            builder.AppendLine("        {");
            builder.AppendLine("            if (Blob == null || Blob.Length < HeaderSize)");
            builder.AppendLine("            {");
            builder.AppendLine("                throw new System.InvalidOperationException(\"String resource is truncated before the header.\");");
            builder.AppendLine("            }");
            builder.AppendLine();
            builder.AppendLine("            var magic = ReadInt32(Blob, 0);");
            builder.AppendLine("            var version = ReadInt32(Blob, 4);");
            builder.AppendLine("            var recordCount = ReadInt32(Blob, 12);");
            builder.AppendLine("            var descriptorOffset = ReadInt32(Blob, 16);");
            builder.AppendLine("            var descriptorLength = ReadInt32(Blob, 20);");
            builder.AppendLine("            var metadataOffset = ReadInt32(Blob, 24);");
            builder.AppendLine("            var metadataLength = ReadInt32(Blob, 28);");
            builder.AppendLine("            var payloadOffset = ReadInt32(Blob, 32);");
            builder.AppendLine("            var payloadLength = ReadInt32(Blob, 36);");
            builder.AppendLine();
            builder.AppendLine("            if (magic != Magic || version != Version)");
            builder.AppendLine("            {");
            builder.AppendLine("                throw new System.InvalidOperationException(\"String resource has an unsupported format.\");");
            builder.AppendLine("            }");
            builder.AppendLine();
            builder.AppendLine("            if (recordCount < 0 || descriptorOffset != HeaderSize || descriptorLength != checked(recordCount * DescriptorSize))");
            builder.AppendLine("            {");
            builder.AppendLine("                throw new System.InvalidOperationException(\"String resource index header is invalid.\");");
            builder.AppendLine("            }");
            builder.AppendLine();
            builder.AppendLine("            ValidateRange(descriptorOffset, descriptorLength, Blob.Length, \"descriptor table\");");
            builder.AppendLine("            ValidateRange(metadataOffset, metadataLength, Blob.Length, \"metadata region\");");
            builder.AppendLine("            ValidateRange(payloadOffset, payloadLength, Blob.Length, \"payload region\");");
            builder.AppendLine();
            builder.AppendLine("            var entries = new Entry[recordCount];");
            builder.AppendLine("            var previousToken = int.MinValue;");
            builder.AppendLine("            for (var i = 0; i < recordCount; i++)");
            builder.AppendLine("            {");
            builder.AppendLine("                var offset = descriptorOffset + i * DescriptorSize;");
            builder.AppendLine("                var entry = new Entry(");
            builder.AppendLine("                    ReadInt32(Blob, offset),");
            builder.AppendLine("                    ReadInt32(Blob, offset + 4),");
            builder.AppendLine("                    ReadInt32(Blob, offset + 8),");
            builder.AppendLine("                    ReadInt32(Blob, offset + 12),");
            builder.AppendLine("                    ReadInt32(Blob, offset + 16),");
            builder.AppendLine("                    ReadInt32(Blob, offset + 20),");
            builder.AppendLine("                    ReadInt32(Blob, offset + 24),");
            builder.AppendLine("                    ReadInt32(Blob, offset + 28),");
            builder.AppendLine("                    ReadInt32(Blob, offset + 32),");
            builder.AppendLine("                    unchecked((uint)ReadInt32(Blob, offset + 36)));");
            builder.AppendLine();
            builder.AppendLine("                if (i > 0 && entry.Token <= previousToken)");
            builder.AppendLine("                {");
            builder.AppendLine("                    throw new System.InvalidOperationException(\"String resource descriptor tokens are not sorted.\");");
            builder.AppendLine("                }");
            builder.AppendLine();
            builder.AppendLine("                if (entry.CacheIndex < 0 || entry.CacheIndex >= recordCount || entry.DecodedCharLength < 0)");
            builder.AppendLine("                {");
            builder.AppendLine("                    throw new System.InvalidOperationException(\"String resource descriptor cache index or length is invalid.\");");
            builder.AppendLine("                }");
            builder.AppendLine();
            builder.AppendLine("                ValidateRange(entry.MetadataOffset, entry.MetadataLength, Blob.Length, \"record metadata\");");
            builder.AppendLine("                ValidateRange(entry.PayloadOffset, entry.PayloadLength, Blob.Length, \"record payload\");");
            builder.AppendLine("                entries[i] = entry;");
            builder.AppendLine("                previousToken = entry.Token;");
            builder.AppendLine("            }");
            builder.AppendLine();
            builder.AppendLine("            Entries = entries;");
            builder.AppendLine("            Cache = new string[recordCount];");
            builder.AppendLine("        }");
            builder.AppendLine();
            builder.AppendLine("        private static int FindEntry(int token)");
            builder.AppendLine("        {");
            builder.AppendLine("            var low = 0;");
            builder.AppendLine("            var high = Entries.Length - 1;");
            builder.AppendLine("            while (low <= high)");
            builder.AppendLine("            {");
            builder.AppendLine("                var middle = low + ((high - low) / 2);");
            builder.AppendLine("                var current = Entries[middle].Token;");
            builder.AppendLine("                if (current == token)");
            builder.AppendLine("                {");
            builder.AppendLine("                    return middle;");
            builder.AppendLine("                }");
            builder.AppendLine();
            builder.AppendLine("                if (current < token)");
            builder.AppendLine("                {");
            builder.AppendLine("                    low = middle + 1;");
            builder.AppendLine("                }");
            builder.AppendLine("                else");
            builder.AppendLine("                {");
            builder.AppendLine("                    high = middle - 1;");
            builder.AppendLine("                }");
            builder.AppendLine("            }");
            builder.AppendLine();
            builder.AppendLine("            return -1;");
            builder.AppendLine("        }");
            builder.AppendLine();
        }

        private static void AppendDecode(StringBuilder builder, ISet<byte> codecs)
        {
            builder.AppendLine("        private static string Decode(Entry entry)");
            builder.AppendLine("        {");
            builder.AppendLine("            var metadata = Slice(Blob, entry.MetadataOffset, entry.MetadataLength);");
            builder.AppendLine("            var payload = Slice(Blob, entry.PayloadOffset, entry.PayloadLength);");
            builder.AppendLine("            byte[] decoded;");
            builder.AppendLine("            switch (entry.CodecId)");
            builder.AppendLine("            {");

            foreach (var codecId in codecs.OrderBy(id => id))
            {
                builder.AppendLine("                case " + codecId.ToString(CultureInfo.InvariantCulture) + ":");
                builder.AppendLine("                    decoded = DecodeCodec" + codecId.ToString(CultureInfo.InvariantCulture) + "(metadata, payload, entry.DecodedCharLength);");
                builder.AppendLine("                    break;");
            }

            builder.AppendLine("                default:");
            builder.AppendLine("                    throw new System.InvalidOperationException(\"String resource codec \" + entry.CodecId.ToString(System.Globalization.CultureInfo.InvariantCulture) + \" is not supported by this loader.\");");
            builder.AppendLine("            }");
            builder.AppendLine();
            builder.AppendLine("            var expectedBytes = checked(entry.DecodedCharLength * 2);");
            builder.AppendLine("            if (decoded.Length != expectedBytes)");
            builder.AppendLine("            {");
            builder.AppendLine("                throw new System.InvalidOperationException(\"String resource decoder returned an unexpected length.\");");
            builder.AppendLine("            }");
            builder.AppendLine();
            builder.AppendLine("            if (ComputeFnv1a32(decoded) != entry.Checksum)");
            builder.AppendLine("            {");
            builder.AppendLine("                throw new System.InvalidOperationException(\"String resource checksum validation failed.\");");
            builder.AppendLine("            }");
            builder.AppendLine();
            builder.AppendLine("            return StringFromUtf16Le(decoded, entry.DecodedCharLength);");
            builder.AppendLine("        }");
            builder.AppendLine();
        }

        private static void AppendCodecMethods(StringBuilder builder, ISet<byte> codecs)
        {
            if (codecs.Contains(1))
            {
                builder.AppendLine("        private static byte[] DecodeCodec1(byte[] metadata, byte[] payload, int charCount)");
                builder.AppendLine("        {");
                builder.AppendLine("            if (metadata.Length == 0) throw new System.InvalidOperationException(\"Invalid XOR metadata.\");");
                builder.AppendLine("            var output = new byte[payload.Length];");
                builder.AppendLine("            for (var i = 0; i < payload.Length; i++) output[i] = (byte)(payload[i] ^ metadata[i % metadata.Length]);");
                builder.AppendLine("            return output;");
                builder.AppendLine("        }");
                builder.AppendLine();
            }

            if (codecs.Contains(2))
            {
                builder.AppendLine("        private static byte[] DecodeCodec2(byte[] metadata, byte[] payload, int charCount)");
                builder.AppendLine("        {");
                builder.AppendLine("            if (metadata.Length != 4) throw new System.InvalidOperationException(\"Invalid LCG metadata.\");");
                builder.AppendLine("            var output = Clone(payload);");
                builder.AppendLine("            ApplyLcgXor(output, ReadUInt32(metadata, 0));");
                builder.AppendLine("            return output;");
                builder.AppendLine("        }");
                builder.AppendLine();
            }

            if (codecs.Contains(3))
            {
                builder.AppendLine("        private static byte[] DecodeCodec3(byte[] metadata, byte[] payload, int charCount)");
                builder.AppendLine("        {");
                builder.AppendLine("            if (metadata.Length != 0) throw new System.InvalidOperationException(\"Invalid GZip metadata.\");");
                builder.AppendLine("            return Decompress(payload);");
                builder.AppendLine("        }");
                builder.AppendLine();
            }

            if (codecs.Contains(4))
            {
                builder.AppendLine("        private static byte[] DecodeCodec4(byte[] metadata, byte[] payload, int charCount)");
                builder.AppendLine("        {");
                builder.AppendLine("            if (metadata.Length != 4) throw new System.InvalidOperationException(\"Invalid GZip LCG metadata.\");");
