                builder.AppendLine("            var inverse = metadata[0];");
                builder.AppendLine("            var offset = metadata[1];");
                builder.AppendLine("            var output = new byte[payload.Length];");
                builder.AppendLine("            for (var i = 0; i < payload.Length; i++) output[i] = (byte)(((payload[i] - offset) * inverse) & 255);");
                builder.AppendLine("            return output;");
                builder.AppendLine("        }");
