                builder.AppendLine("        }");
                builder.AppendLine();
            }

            if (codecs.Contains(14))
            {
                builder.AppendLine("        private static byte[] DecodeCodec14(byte[] metadata, byte[] payload, int charCount)");
                builder.AppendLine("        {");
                builder.AppendLine("            var expected = checked(charCount * 2);");
                builder.AppendLine("            if (metadata.Length != 1 || payload.Length != checked(expected + 1) || payload[payload.Length - 1] != 1) throw new System.InvalidOperationException(\"Invalid BigInteger packing payload.\");");
                builder.AppendLine("            var output = new byte[expected];");
                builder.AppendLine("            for (var i = 0; i < output.Length; i++) output[i] = (byte)(payload[i] ^ metadata[0]);");
