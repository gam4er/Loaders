                builder.AppendLine("            var expected = checked(charCount * 2);");
                builder.AppendLine("            if (metadata.Length != 1 || payload.Length != checked(expected * 3)) throw new System.InvalidOperationException(\"Invalid junked payload.\");");
                builder.AppendLine("            var output = new byte[expected];");
                builder.AppendLine("            for (var i = 0; i < output.Length; i++) output[i] = (byte)(payload[i * 3] ^ metadata[0]);");
