                builder.AppendLine("            for (var i = 0; i < payload.Length; i++) output[i] = (byte)(payload[payload.Length - i - 1] ^ metadata[0]);");
                builder.AppendLine("            return output;");
                builder.AppendLine("        }");
                builder.AppendLine();
            }

            if (codecs.Contains(6))
            {
                builder.AppendLine("        private static byte[] DecodeCodec6(byte[] metadata, byte[] payload, int charCount)");
                builder.AppendLine("        {");
                builder.AppendLine("            if (metadata.Length != 8) throw new System.InvalidOperationException(\"Invalid decimal delta metadata.\");");
                builder.AppendLine("            var expected = checked(charCount * 2);");
                builder.AppendLine("            if (payload.Length != checked(expected * 2)) throw new System.InvalidOperationException(\"Invalid decimal delta payload length.\");");
                builder.AppendLine("            var seed = ReadInt32(metadata, 0);");
                builder.AppendLine("            var step = ReadInt32(metadata, 4);");
                builder.AppendLine("            var output = new byte[expected];");
                builder.AppendLine("            for (var i = 0; i < output.Length; i++)");
                builder.AppendLine("            {");
                builder.AppendLine("                var encoded = ReadUInt16(payload, i * 2);");
                builder.AppendLine("                var mask = 256 + (int)((seed + (long)i * step) % 997);");
                builder.AppendLine("                output[i] = checked((byte)(encoded - mask));");
                builder.AppendLine("            }");
                builder.AppendLine("            return output;");
                builder.AppendLine("        }");
                builder.AppendLine();
            }

            if (codecs.Contains(7))
